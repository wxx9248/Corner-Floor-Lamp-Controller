#!/usr/bin/env python3
"""Regenerate src/duoco_stripx/effects.py from the decompiled app's arrays.xml.

Usage: python scripts/gen_effects.py <path-to-arrays.xml>

arrays.xml lives in the decompiled APK at
re/jadx-out/resources/res/values/arrays.xml and uses <array> elements (NOT
<string-array>): modes_group0..7 (+ _command) are the 213 animation modes,
modes_group8 (+ _command) is the 28-entry Scenes list (sent via changeScene).

Four animation names appear twice with different ids (app duplication in
groups 6/7); those get an " (id)" suffix so the name->id map is total.
"""
from __future__ import annotations

import re
import sys
from collections import Counter
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "src" / "duoco_stripx" / "effects.py"

HEADER = '''"""Effect and scene ID tables for duoCo StripX.

AUTO-GENERATED by scripts/gen_effects.py from the decompiled app's
res/values/arrays.xml (modes_group0..7 = animation modes for changeMode,
modes_group8 = scenes for changeScene). Do not edit by hand.

Names duplicated in the app (4 cases in groups 6/7) carry an " (id)" suffix
so the reverse maps are total.
"""
from __future__ import annotations

'''


def parse_array(xml: str, name: str) -> list[str]:
    m = re.search(r'<array name="%s">(.*?)</array>' % re.escape(name), xml, re.S)
    if not m:
        raise SystemExit(f"array {name!r} not found")
    return re.findall(r"<item>(.*?)</item>", m.group(1), re.S)


def main() -> None:
    if len(sys.argv) != 2:
        raise SystemExit(__doc__)
    xml = Path(sys.argv[1]).read_text()

    animations: dict[int, str] = {}
    for g in range(8):
        names = parse_array(xml, f"modes_group{g}")
        ids = [int(x) for x in parse_array(xml, f"modes_group{g}_command")]
        if len(names) != len(ids):
            raise SystemExit(f"group{g}: name/command length mismatch")
        for n, i in zip(names, ids):
            if i in animations:
                raise SystemExit(f"duplicate mode id {i}")
            animations[i] = n

    # Disambiguate duplicated names (same name, different ids).
    counts = Counter(animations.values())
    for i, n in animations.items():
        if counts[n] > 1:
            animations[i] = f"{n} ({i})"

    scene_names = parse_array(xml, "modes_group8")
    scene_ids = [int(x) for x in parse_array(xml, "modes_group8_command")]
    scenes = dict(zip(scene_ids, scene_names))

    assert len(animations) == 213, len(animations)
    assert len(scenes) == 28, len(scenes)
    assert len(set(animations.values())) == 213, "animation names not unique"
    assert len(set(scenes.values())) == 28, "scene names not unique"

    with OUT.open("w") as f:
        f.write(HEADER)
        f.write("ANIMATION_MODES: dict[int, str] = {\n")
        for i in sorted(animations):
            f.write(f"    {i}: {animations[i]!r},\n")
        f.write("}\n\nSCENES: dict[int, str] = {\n")
        for i in sorted(scenes):
            f.write(f"    {i}: {scenes[i]!r},\n")
        f.write(
            "}\n\n"
            "ANIMATION_NAME_TO_ID: dict[str, int] = "
            "{v: k for k, v in ANIMATION_MODES.items()}\n"
            "SCENE_NAME_TO_ID: dict[str, int] = {v: k for k, v in SCENES.items()}\n"
        )
    print(f"wrote {OUT} ({len(animations)} modes, {len(scenes)} scenes)")


if __name__ == "__main__":
    main()
